const J = (id, sourceId, sourceTitle, sourceType, operation, status, createdDays, retries, extra = {}) => ({
  id,
  sourceId,
  sourceTitle,
  sourceType,
  operation,
  status,
  createdAt: daysAgo(createdDays, extra.hour ?? 3, extra.minute ?? 0),
  completedAt:
    status === 'completed' || status === 'failed'
      ? daysAgo(createdDays, extra.hour ?? 3, (extra.minute ?? 0) + 2)
      : null,
  retryCount: retries,
  errorSummary: extra.error ?? '',
  log: extra.log ?? [],
});

