const locById = Object.fromEntries(mockLocations.map((l) => [l.id, l]));

function locationFor(placeId, address) {
  const place = locById[placeId];
  const city = place.type === 'neighborhood' ? locById[place.parentId] : place;
  const region = locById[city.parentId];
  return {
    countryId: 'loc-barbados',
    regionId: region.id,
    cityId: city.id,
    neighborhoodId: place.type === 'neighborhood' ? place.id : '',
    address,
    postalCode: '',
    lat: Number((place.lat + 0.002).toFixed(4)),
    lng: Number((place.lng - 0.002).toFixed(4)),
    displayPreference: 'area',
  };
}

